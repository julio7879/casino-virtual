export function getRandomChallenge(excludeId?: string): TournamentChallenge {
  const pool = excludeId
    ? TOURNAMENT_CHALLENGES.filter((c) => c.id !== excludeId)
    : TOURNAMENT_CHALLENGES;
  return pool[Math.floor(Math.random() * pool.length)];
}
